"""Extract the KB documents (Appendix D) and the requirement rows (sections 4-5) from the spec.

Run: uv run python scripts/extract_spec.py
Writes kb/docs/<doc_id>.md and docs/requirements-map.md (statuses start as "Not started").
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = (ROOT / "requirements-and-benchmarks.md").read_text()

# Requirement id -> (component, phase). Edit as the build moves.
COMPONENT = [
    (r"^R-5\.|^B-08$", "mail", 6),
    (r"^B-04$|^R-4\.8\.", "kb", 3),
    (r"^R-4\.6\.|^B-1[01]$|^R-4\.2\.3$|^B-12$", "guards", 4),
    (r"^R-4\.3\.|^R-4\.4\.|^B-0[23]$|^B-19$|^B-21$", "memory", 5),
    (r"^R-4\.2\.|^B-09$|^B-23$|^R-4\.9\.|^R-4\.12\.", "observability", 3),
    (r"^B-0[5-7]$|^R-4\.5\.2$|^R-4\.7\.[14]$|^B-17$|^B-22$", "gateway", 1),
    (r"^R-4\.1\.[23]$", "scaling", 8),
    (r"^R-4\.10\.|^R-4\.5\.[18]$", "release", 11),
]


def extract_kb() -> int:
    out = ROOT / "kb" / "docs"
    out.mkdir(parents=True, exist_ok=True)
    docs = re.findall(r"^### D\.([\w-]+)\n\n````markdown\n(.*?)\n````", SPEC, flags=re.S | re.M)
    for doc_id, body in docs:
        (out / f"{doc_id}.md").write_text(body + "\n")
    return len(docs)


def extract_requirements() -> int:
    rows = []
    section = ""
    for line in SPEC.split("## 5.7")[0].splitlines():
        if line.startswith("### 4.") or line.startswith("### 5."):
            section = line.removeprefix("### ")
        m = re.match(r"^\| ((?:R-\d\.\d+\.\d+)|(?:B-\d{2})) \| ([^|]+) \| ([^|]+) \|", line)
        if m:
            rid, level, req = (s.strip() for s in m.groups())
            ref = line.rstrip(" |").rsplit("|", 1)[-1].strip()
            component, phase = next(((c, p) for pat, c, p in COMPONENT if re.search(pat, rid)), ("app", 2))
            status = "Waived" if ref == "Waived" else "Not started"
            rows.append((rid, level, section, req, component, phase, status))
    lines = [
        "# Requirements map",
        "",
        "Every row of spec sections 4 and 5 (generated by `scripts/extract_spec.py`, then edited by hand).",
        "Status: Not started, In progress, Pass, Partial, Fail, Waived. Evidence = test name, case id or run record.",
        "",
        f"Rows: {len(rows)} · MUST: {sum(r[1].startswith('MUST') for r in rows)} · "
        f"SHOULD: {sum(r[1] == 'SHOULD' for r in rows)}",
        "",
        "| ID | Level | Section | Requirement | Component | Phase | Status | Evidence |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for rid, level, section, req, component, phase, status in rows:
        lines.append(f"| {rid} | {level} | {section.split(' ')[0]} | {req} | {component} | {phase} | {status} | |")
    (ROOT / "docs" / "requirements-map.md").write_text("\n".join(lines) + "\n")
    return len(rows)


if __name__ == "__main__":
    print("kb docs:", extract_kb())
    print("requirement rows:", extract_requirements())
